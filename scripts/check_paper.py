"""Structural checks on the paper's sources, before anything is built.

    python scripts/check_paper.py

Two things are checked, because there are two documents and only one of them is the
paper.

`docs/paper/PRAXIS_IEEE.docx` is the submitted artifact. It is generated by
`scripts/build_paper_docx.py` from the result files, so what can be checked *here* is
that the build has everything it needs: the template, the result files, the figures,
and a generating script for each figure the paper embeds. The built document itself is
checked by `scripts/verify_claims.py`, which reads the .docx and compares every
quantity in it against the records.

`docs/paper/main.tex` is an earlier LaTeX draft, kept for reference and **not** the
source of the PDF. It is checked for the mistakes that are cheap to make while editing
a .tex - unbalanced environments, references to labels that do not exist, citations
with no bibliography entry - and nothing here implies it compiles, because no TeX
installation is assumed.

Exits non-zero on any problem, so it can gate a build.
"""
from __future__ import annotations

import re
import sys

from _paths import ROOT, show

PAPER = ROOT / "docs/paper"
DOCX = PAPER / "PRAXIS_IEEE.docx"
TEMPLATE = PAPER / "templates/ieee_a4_transitional.docx"

# Each figure the paper embeds, and the script that produces it. The build is the
# only thing that reads these files, so a figure arriving by any other route - drawn
# by hand, exported from a tool, copied in from elsewhere - is a figure nobody can
# regenerate. Keeping the mapping here makes that checkable rather than assumed.
FIGURES = {
    "architecture.png": "scripts/make_architecture_figure.py",
    "main_results.png": "scripts/make_results_figure.py",
}

REQUIRED_RESULTS = [
    "eval_reports/research/paper/test.report.json",
    "eval_reports/research/confirm/confirm.report.json",
    "eval_reports/research/paper/test.neurosymbolic.jsonl",
    "eval_reports/research/paper/test.ns_parser.jsonl",
    "eval_reports/research/gate-ablation-v3/test.neurosymbolic_llm.jsonl",
    "eval_reports/research/gate-ablation-v3/test.neurosymbolic_llm_no_verification.jsonl",
    "artifacts/verification_checks.json",
    "backend/data/benchmark_worlds/test.yaml",
]

problems: list[str] = []


def fail(message: str) -> None:
    problems.append(message)
    print(f"  FAIL  {message}")


def ok(message: str) -> None:
    print(f"  ok    {message}")


# ---------------------------------------------------------------------------
# 1. the paper that is actually submitted
# ---------------------------------------------------------------------------
print("docx build inputs")

if TEMPLATE.exists():
    ok(f"IEEE template present: {show(TEMPLATE)}")
else:
    fail(f"missing template {show(TEMPLATE)} - the build supplies no styling of its own")

for rel in REQUIRED_RESULTS:
    path = ROOT / rel
    if path.exists():
        ok(f"result file present: {rel}")
    else:
        fail(f"missing result file {rel} - the build refuses to emit a placeholder")

builder = (ROOT / "scripts/build_paper_docx.py").read_text(encoding="utf-8")
embedded = set(re.findall(r'FIGURES / "([^"]+)"', builder))
if not embedded:
    fail("no figures found in build_paper_docx.py - has the embedding changed?")
for name in sorted(embedded):
    generator = FIGURES.get(name)
    if generator is None:
        fail(f"{name} is embedded in the paper but no script here is named as its "
             f"source; add it to FIGURES in this file")
    elif not (ROOT / generator).exists():
        fail(f"{name} names {generator} as its source and that file does not exist")
    elif not (PAPER / "figures" / name).exists():
        fail(f"{name} has not been generated; run {generator}")
    else:
        ok(f"{name} <- {generator}")
for name in sorted(set(FIGURES) - embedded):
    fail(f"{name} is listed as a paper figure here but the paper no longer embeds it")

if DOCX.exists():
    ok(f"built paper present: {show(DOCX)}")
else:
    print(f"  note  {show(DOCX)} not built yet; run scripts/build_paper.py")

# ---------------------------------------------------------------------------
# 2. the LaTeX draft, which is not the paper
# ---------------------------------------------------------------------------
tex_path, bib_path = PAPER / "main.tex", PAPER / "references.bib"
if not tex_path.exists():
    print("\nno main.tex - skipping the LaTeX draft checks")
else:
    print(f"\nLaTeX draft ({show(tex_path)}; reference only, not the submitted paper)")
    tex = tex_path.read_text(encoding="utf-8")
    bib = bib_path.read_text(encoding="utf-8") if bib_path.exists() else ""

    # Strip comments so a commented-out \begin does not count.
    body = "\n".join(re.sub(r"(?<!\\)%.*$", "", line) for line in tex.splitlines())
    n_sec = len(re.findall(r"\\section\{", body))
    n_sub = len(re.findall(r"\\subsection\{", body))
    print(f"  lines: {len(tex.splitlines())}  sections: {n_sec}  "
          f"subsections: {n_sub}")

    for env in ("document", "abstract", "table", "itemize", "enumerate", "figure",
                "equation", "align", "tabular"):
        opened = len(re.findall(r"\\begin\{" + env + r"\}", body))
        closed = len(re.findall(r"\\end\{" + env + r"\}", body))
        if opened != closed:
            fail(f"unbalanced {env}: {opened} begin, {closed} end")

    labels = set(re.findall(r"\\label\{([^}]+)\}", body))
    refs = set(re.findall(r"\\ref\{([^}]+)\}", body))
    for missing in sorted(refs - labels):
        fail(f"\\ref to a label that does not exist: {missing}")

    keys = set(re.findall(r"@\w+\{([^,]+),", bib))
    cited: set[str] = set()
    for group in re.findall(r"\\cite[tp]?\{([^}]+)\}", body):
        cited.update(k.strip() for k in group.split(","))
    for missing in sorted(cited - keys):
        fail(f"cited but not in references.bib: {missing}")
    unused = sorted(keys - cited)
    print(f"  labels: {len(labels)}  refs: {len(refs)}  bib entries: {len(keys)}  "
          f"cited: {len(cited)}")
    if unused:
        print(f"  note  in references.bib, never cited: {', '.join(unused)}")

print()
if problems:
    print(f"{len(problems)} problem(s) above")
    sys.exit(1)
print("every check passed")
