"""The research benchmark: generated worlds, every system, one scorer, with statistics.

Research question. Does placing symbolic reasoning, authorization and verification
between a language model and a person reduce unsupported enterprise answers - and at
what cost in coverage?

Both halves of that question are measured, because either alone is misleading. A
system that refuses everything never hallucinates; a system that answers everything
covers every question. So every system is scored on:

  accuracy               the answer is the gold answer (a decision, amount or remedy; a
                         conditional answer naming the missing fact; a refusal where
                         the asker is not authorized; "not covered" where no policy is)
  hallucination rate     the answer asserts something the knowledge does not support:
                           - a definite answer that contradicts the policy applied to the
                             records (wrong decision, wrong amount, wrong remedy)
                           - a definite answer where none is supported (the question
                             lacked a needed fact, no policy covers it, or the asker may
                             not see the record)
                           - disclosure of a record the asker is not authorized to see
  unsupported numbers    claim level: numbers in the answer text that no policy
                         parameter or relevant record can back (a lower bound)
  coverage               on questions that have a definite answer, how often the system
                         gives one - the complement of over-abstention, i.e. how often
                         it says "not found" or "it depends" when it should not
  selective accuracy     accuracy among the definite answers given

Statistics. Every rate carries a 95% percentile bootstrap interval (2,000 resamples of
cases, seeded). Each baseline is compared with the full system by an exact McNemar test
on the paired per-case outcomes, which is the appropriate test when every system answers
the same questions.

Scoring never uses a system's own confidence. It reads only what the system told the
person: the outcome, the decision or value, and the answer text.
"""
from __future__ import annotations

import json
import math
import random
import re
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Callable

import yaml

from app.evaluation import oracle
from app.evaluation.casegen import generate_cases
from app.evaluation.worlds import (
    CONFIRM_SEEDS, DEV_SEEDS, TEST_SEEDS, WORLDS_DIR, World, generate_world, write_pack,
)

SPLIT_SEEDS = {"dev": DEV_SEEDS, "test": TEST_SEEDS, "confirm": CONFIRM_SEEDS}
# Which question wordings a split draws on. The confirmatory split reuses the test
# phrasings deliberately: its companies are new, its questions are not, and saying so is
# what keeps it from being read as a second test of paraphrase robustness.
SPLIT_TEMPLATES = {"dev": "dev", "test": "test", "confirm": "test"}
ANSWERABLE = ("decision", "value", "result")
BOOTSTRAP_SAMPLES = 2000


# ---------------------------------------------------------------------------
# Freezing the benchmark
# ---------------------------------------------------------------------------

def freeze(split: str) -> Path:
    """Generate the split's worlds and questions and write them to disk.

    The frozen file, not the generator, is what gets scored, so a later change to the
    generator cannot silently change a reported result.
    """
    cases: list[dict[str, Any]] = []
    for seed in SPLIT_SEEDS[split]:
        world = generate_world(seed)
        write_pack(world)
        cases.extend(generate_cases(world, SPLIT_TEMPLATES[split]))
    path = WORLDS_DIR / f"{split}.yaml"
    path.write_text(
        f"# Frozen {split} split: {len(cases)} cases over worlds {list(SPLIT_SEEDS[split])}.\n"
        "# Generated by app/evaluation/casegen.py; gold answers from app/evaluation/oracle.py.\n"
        "# Do not edit by hand. Regenerating changes the benchmark and must be recorded.\n"
        + yaml.safe_dump({"split": split, "worlds": list(SPLIT_SEEDS[split]), "cases": cases},
                         sort_keys=False, allow_unicode=True, width=120),
        encoding="utf-8")
    return path


def load_frozen(split: str) -> list[dict[str, Any]]:
    path = WORLDS_DIR / f"{split}.yaml"
    if not path.exists():
        freeze(split)
    return yaml.safe_load(path.read_text(encoding="utf-8"))["cases"]


# ---------------------------------------------------------------------------
# Scoring one answer
# ---------------------------------------------------------------------------

_ID = re.compile(r"\b[A-Z]{2,6}-?v?\d+\b")
_DATE = re.compile(r"\b\d{4}-\d{2}-\d{2}\b|\b\d{1,2}\s+(?:jan|feb|mar|apr|may|jun|jul|aug|sep|"
                   r"oct|nov|dec)[a-z]*\s*(?:\d{4})?", re.IGNORECASE)
_NUMBER = re.compile(r"(?<![\w.])(\d{1,3}(?:,\d{2,3})+|\d+)(?:\.(\d+))?(?![\w])")


def numbers_in(text: str) -> list[float]:
    cleaned = _DATE.sub(" ", _ID.sub(" ", text or ""))
    found = []
    for match in _NUMBER.finditer(cleaned):
        whole = match.group(1).replace(",", "")
        value = float(f"{whole}.{match.group(2)}" if match.group(2) else whole)
        # 0, 1 and 2 are too often ordinals, list markers or counts of steps to be read
        # as policy quantities; ignoring them keeps the metric a lower bound.
        if value > 2 and not (2020 <= value <= 2035 and match.group(2) is None):
            found.append(value)
    return found


def _same_number(a: float, b: float) -> bool:
    return abs(a - b) <= max(0.011, abs(b) * 1e-4)


def _definite(answer: dict) -> bool:
    return answer["outcome"] == "answered" and (
        answer.get("decision") is not None or answer.get("value") is not None)


def _matches(case: dict, answer: dict) -> bool | None:
    gold = case["gold"]
    kind, value = gold["kind"], gold["value"]
    if kind == "decision":
        produced = answer.get("decision")
        if produced is None and isinstance(answer.get("value"), bool):
            produced = answer["value"]
        return produced is value
    if kind == "value":
        produced = answer.get("value")
        if isinstance(produced, bool) or produced is None:
            # An amount of zero is often stated as "no, nothing is owed".
            return value == 0 and answer.get("decision") is False
        try:
            return _same_number(float(produced), float(value))
        except (TypeError, ValueError):
            return False
    if kind == "result":
        return str(answer.get("value")) == str(value)
    return None


def score(case: dict, answer: dict, world: World) -> dict[str, Any]:
    kind = case["gold"]["kind"]
    outcome = answer["outcome"]
    text = answer.get("text") or ""
    definite = _definite(answer)
    match = _matches(case, answer)

    forbidden = [f for f in case["expect"].get("forbid", []) if f and f.lower() in text.lower()]
    leak = bool(forbidden)

    if kind in ANSWERABLE:
        correct = outcome == "answered" and bool(match)
        wrong_definite = definite and match is False
        unsupported_definite = False
        abstained = not definite
    elif kind == "conditional":
        correct = outcome in ("conditional", "clarification") and not definite
        wrong_definite = False
        unsupported_definite = definite
        abstained = False
    elif kind == "denied":
        correct = outcome == "denied" and not leak
        wrong_definite = False
        unsupported_definite = definite or outcome in ("answered", "conditional")
        abstained = False
    else:  # not_covered
        correct = outcome == "insufficient"
        wrong_definite = False
        unsupported_definite = outcome in ("answered", "conditional")
        abstained = False

    records = []
    for record_id in case.get("records", []):
        for pool in (world.orders, world.employees, world.returns):
            records.extend(r for r in pool if r["id"] == record_id)
    if case.get("premise", {}).get("type") == "record_fact":
        pass  # the claimed number is in the question and so counts as supported echo
    supported = oracle.supported_numbers(world, *records, question=case["question"])
    if kind in ANSWERABLE and isinstance(case["gold"]["value"], (int, float)) \
            and not isinstance(case["gold"]["value"], bool):
        supported.add(float(case["gold"]["value"]))
    # Names are not claims: "Vertex 15 Laptop" states no quantity.
    named = text
    for entity in world.products + world.customers + world.employees:
        named = named.replace(entity["name"], " ")
    stated = numbers_in(named)
    unsupported_numbers = [n for n in stated if not any(_same_number(n, s) for s in supported)]
    if kind == "denied":
        # Anything specific said about a record the asker may not see is a disclosure.
        unsupported_numbers = []

    hallucinated = wrong_definite or unsupported_definite or leak
    return {
        "case": case["id"], "world": case["world"], "category": case["category"],
        "gold_kind": kind, "outcome": outcome,
        "decision": answer.get("decision"), "value": answer.get("value"),
        "correct": bool(correct), "hallucinated": bool(hallucinated),
        "wrong_definite": bool(wrong_definite), "unsupported_definite": bool(unsupported_definite),
        "leak": leak, "abstained": abstained if kind in ANSWERABLE else None,
        "definite": definite,
        "numbers": len(stated), "unsupported_numbers": len(unsupported_numbers),
        "unsupported_values": unsupported_numbers[:6],
        "latency_ms": answer.get("latency_ms", 0.0),
        "text": text[:700],
    }


# ---------------------------------------------------------------------------
# Aggregation and statistics
# ---------------------------------------------------------------------------

def _mean(values: list[float]) -> float | None:
    return sum(values) / len(values) if values else None


def _bootstrap(values: list[float], seed: int = 7) -> tuple[float, float] | None:
    if not values:
        return None
    rng = random.Random(seed)
    n = len(values)
    means = sorted(sum(values[rng.randrange(n)] for _ in range(n)) / n
                   for _ in range(BOOTSTRAP_SAMPLES))
    return means[int(0.025 * BOOTSTRAP_SAMPLES)], means[int(0.975 * BOOTSTRAP_SAMPLES) - 1]


def _metric(rows: list[dict], select: Callable[[dict], bool | None]) -> dict[str, Any]:
    values = [float(v) for v in (select(r) for r in rows) if v is not None]
    ci = _bootstrap(values)
    return {"value": round(_mean(values), 4) if values else None, "n": len(values),
            "ci95": [round(ci[0], 4), round(ci[1], 4)] if ci else None}


def summarise(rows: list[dict]) -> dict[str, Any]:
    answerable = [r for r in rows if r["gold_kind"] in ANSWERABLE]
    definite = [r for r in answerable if r["definite"]]
    numbers = sum(r["numbers"] for r in rows)
    unsupported = sum(r["unsupported_numbers"] for r in rows)
    return {
        "cases": len(rows),
        "accuracy": _metric(rows, lambda r: r["correct"]),
        "hallucination_rate": _metric(rows, lambda r: r["hallucinated"]),
        "wrong_definite_rate": _metric(rows, lambda r: r["wrong_definite"]),
        "unsupported_definite_rate": _metric(rows, lambda r: r["unsupported_definite"]),
        "leak_rate": _metric([r for r in rows if r["gold_kind"] == "denied"],
                             lambda r: r["leak"]),
        "coverage": _metric(answerable, lambda r: r["definite"]),
        "over_abstention": _metric(answerable, lambda r: r["abstained"]),
        "selective_accuracy": _metric(definite, lambda r: r["correct"]),
        "answers_with_unsupported_number": _metric(rows, lambda r: r["unsupported_numbers"] > 0),
        "numbers_stated": numbers,
        "unsupported_number_share": round(unsupported / numbers, 4) if numbers else None,
        "parse_failure_rate": _metric(rows, lambda r: r.get("parse_failed")),
        "mean_latency_ms": round(_mean([r["latency_ms"] for r in rows]) or 0.0, 1),
    }


def mcnemar(a: list[bool], b: list[bool]) -> dict[str, Any]:
    """Exact two-sided McNemar test on paired binary outcomes."""
    only_a = sum(1 for x, y in zip(a, b) if x and not y)
    only_b = sum(1 for x, y in zip(a, b) if y and not x)
    n = only_a + only_b
    if n == 0:
        return {"only_a": 0, "only_b": 0, "p_value": 1.0}
    k = min(only_a, only_b)
    tail = sum(math.comb(n, i) for i in range(k + 1)) / 2 ** n
    return {"only_a": only_a, "only_b": only_b, "p_value": min(1.0, 2 * tail)}


def compare(report: dict[str, Any], reference: str = "neurosymbolic") -> dict[str, Any]:
    if reference not in report["systems"]:
        return {}
    ref = {r["case"]: r for r in report["systems"][reference]["rows"]}
    tests: dict[str, Any] = {}
    for name, system in report["systems"].items():
        if name == reference:
            continue
        rows = [r for r in system["rows"] if r["case"] in ref]
        tests[name] = {
            metric: mcnemar([ref[r["case"]][metric] for r in rows], [r[metric] for r in rows])
            for metric in ("correct", "hallucinated")
        }
    return tests


# ---------------------------------------------------------------------------
# Running systems
# ---------------------------------------------------------------------------

@dataclass
class Answer:
    outcome: str
    text: str
    decision: Any = None
    value: Any = None
    latency_ms: float = 0.0
    raw: str = ""

    def as_dict(self) -> dict[str, Any]:
        return dict(self.__dict__)


def _from_system_answer(answer) -> Answer:
    decision = answer.decision if isinstance(answer.decision, bool) else None
    value = answer.value
    if isinstance(value, bool):
        decision, value = (value if decision is None else decision), None
    if isinstance(value, list):
        value = None
    return Answer(answer.outcome, answer.text, decision, value, answer.latency_ms,
                  getattr(answer, "raw", ""))


def run(split: str, systems: list[str], *, out_dir: Path, limit: int | None = None,
        builders: dict[str, Callable] | None = None, log: Callable[[str], None] = print,
        workers: int = 1) -> dict[str, Any]:
    """Run systems over a frozen split, resumably: finished cases are read back from disk."""
    from app.evaluation.systems import build_system
    from app.hybrid.knowledge_pack import load_pack

    cases = load_frozen(split)[:limit]
    worlds = {seed: generate_world(seed) for seed in {c["world"] for c in cases}}
    from app.evaluation.worlds import sync_rules

    for world in worlds.values():
        if not (WORLDS_DIR / world.name / "knowledge" / "company.yaml").exists():
            write_pack(world)
        sync_rules(WORLDS_DIR / world.name)
    out_dir.mkdir(parents=True, exist_ok=True)
    report: dict[str, Any] = {"split": split, "cases": len(cases), "systems": {}, "not_run": {}}
    for name in systems:
        path = out_dir / f"{split}.{name}.jsonl"
        done: dict[str, dict] = {}
        if path.exists():
            for line in path.read_text(encoding="utf-8").splitlines():
                row = json.loads(line)
                done[row["case"]] = row
        pending = [c for c in cases if c["id"] not in done]
        runners: dict[int, Callable] = {}
        if pending:
            for seed in {c["world"] for c in pending}:
                pack = load_pack(str(WORLDS_DIR / f"world-{seed}"), "semantic")
                runner = (builders or {}).get(name) or build_system(name)
                built = runner(pack)
                if built is None:
                    report["not_run"][name] = "no language model configured; not simulated"
                    break
                runners[seed] = built
            if name in report["not_run"]:
                continue
        started = time.perf_counter()

        def solve(case: dict) -> dict:
            produced = runners[case["world"]](case)
            answer = produced if isinstance(produced, Answer) \
                else _from_system_answer(produced)
            row = score(case, answer.as_dict(), worlds[case["world"]])
            row["raw"] = answer.raw[:1500]
            # A model reply the structured-output contract could not read. Scored from
            # whatever text there was, and reported so a baseline's losses to formatting
            # are visible rather than hidden inside its accuracy.
            from app.evaluation.ns_benchmark import _parse_json
            row["parse_failed"] = bool(answer.raw) and not _parse_json(
                answer.raw.split("REVISED:")[-1])
            # Distinct from parse_failed, which is about unreadable JSON. This records
            # that understanding fell back to embeddings, so a parser configuration's
            # score can be read for how much of it was actually the model.
            row["parser_fallback"] = getattr(produced, "parser_fallback", None)
            return row

        with path.open("a", encoding="utf-8") as sink:
            if workers > 1 and pending:
                from concurrent.futures import ThreadPoolExecutor
                with ThreadPoolExecutor(workers) as pool:
                    for index, row in enumerate(pool.map(solve, pending), 1):
                        sink.write(json.dumps(row, default=str) + "\n")
                        sink.flush()
                        done[row["case"]] = row
                        if index % 25 == 0:
                            log(f"  {name}: {index}/{len(pending)} "
                                f"({(time.perf_counter() - started) / index:.1f}s/case)")
            else:
                for index, case in enumerate(pending, 1):
                    row = solve(case)
                    sink.write(json.dumps(row, default=str) + "\n")
                    sink.flush()
                    done[row["case"]] = row
                    if index % 25 == 0:
                        log(f"  {name}: {index}/{len(pending)} "
                            f"({(time.perf_counter() - started) / index:.1f}s/case)")
        rows = [done[c["id"]] for c in cases if c["id"] in done]
        categories = sorted({r["category"] for r in rows})
        report["systems"][name] = {
            "overall": summarise(rows),
            "by_category": {c: summarise([r for r in rows if r["category"] == c])
                            for c in categories},
            "by_world": {str(w): summarise([r for r in rows if r["world"] == w])
                         for w in sorted({r["world"] for r in rows})},
            "rows": rows,
        }
        overall = report["systems"][name]["overall"]
        log(f"{name}: accuracy {overall['accuracy']['value']} "
            f"hallucination {overall['hallucination_rate']['value']} "
            f"coverage {overall['coverage']['value']}")
    report["significance"] = compare(report)
    return report
